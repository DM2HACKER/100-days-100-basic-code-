
arr = [12, 45, 2, 89]

# 01. Find Maximum Element
print(f"the Maximum value in this array is : {max(arr)}")

# 02. Find Minimum Element
print(f"the Minimum value in this array is : {min(arr)}")

# 03. Reverse a List
print(f"the reverse array : {arr[::-1]}")

# 04. Sum of Elements
print(f"the sum of the array is : {sum(arr)}")

# 05. Average of Elements
print(f"the average of array is : {sum(arr) / len(arr)}")
